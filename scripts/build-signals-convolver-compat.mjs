// Regenerate the standard-SIMD fallback from the exact installed Signals 0.10.1 bytes.
// Usage: node scripts/build-signals-convolver-compat.mjs /path/to/wabt@1.0.37/index.js
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { CONVOLVER } from "../node_modules/@jtarrio/signals/dist/wasm/wasm-bytes.js";

const expectedInput =
  "5f00919c79db247f79d3f479264c455a469e804707f39c06b41893b77b2135db";
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
if (digest(CONVOLVER) !== expectedInput)
  throw new Error(
    "Signals convolver bytes changed; review the compatibility adaptation before regenerating.",
  );
if (!process.argv[2])
  throw new Error(
    "Supply the path to wabt@1.0.37/index.js (install in a separate tool directory).",
  );
const toolUrl = pathToFileURL(process.argv[2]);
const toolPackage = JSON.parse(
  await readFile(new URL("package.json", toolUrl), "utf8"),
);
if (toolPackage.version !== "1.0.37")
  throw new Error("Use pinned wabt 1.0.37 for reproducible output.");
const wabt = await (await import(toolUrl.href)).default();
const original = wabt.readWasm(CONVOLVER, {
  readDebugNames: true,
  simd: true,
  relaxed_simd: true,
});
original.generateNames();
original.applyNames();
const wat = original.toText({ foldExprs: false, inlineExport: false });
const instructions = wat.match(/f32x4\.relaxed_madd/g) ?? [];
if (instructions.length !== 4)
  throw new Error(
    "Expected exactly four reviewed relaxed multiply-add instructions.",
  );
const compatibleWat = wat
  .replace(/f32x4\.relaxed_madd/g, "call $browserSdrMultiplyAdd")
  .replace(
    /\)\s*$/,
    `
  (func $browserSdrMultiplyAdd (param v128 v128 v128) (result v128)
    local.get 0
    local.get 1
    f32x4.mul
    local.get 2
    f32x4.add)
)`,
  );
// Parsing with relaxed SIMD disabled rejects any remaining relaxed instructions.
const compatible = wabt.parseWat(
  "signals-convolver-standard.wat",
  compatibleWat,
  { simd: true, relaxed_simd: false },
);
compatible.validate({ simd: true, relaxed_simd: false });
const { buffer } = compatible.toBinary({
  canonicalize_lebs: true,
  write_debug_names: false,
});
if (!WebAssembly.validate(buffer))
  throw new Error("Generated convolver failed host validation.");
const rows = [];
for (let offset = 0; offset < buffer.length; offset += 16)
  rows.push(`  ${Array.from(buffer.slice(offset, offset + 16)).join(", ")},`);
const output = `// Copyright 2026 Jacobo Tarrio Barreiro. All rights reserved.
// Licensed under the Apache License, Version 2.0. See THIRD_PARTY_NOTICES.md.
// Adapted by BrowserSDR: four relaxed f32x4 multiply-adds use standard mul + add.
// Generated by scripts/build-signals-convolver-compat.mjs with wabt 1.0.37.
// Signals 0.10.1 input SHA-256: ${expectedInput}
// Output SHA-256: ${digest(buffer)}
export const STANDARD_CONVOLVER = new Uint8Array([
${rows.join("\n")}
]);
`;
await writeFile(
  new URL("../src/dsp/signalsConvolverBytes.ts", import.meta.url),
  output,
);
console.log(
  JSON.stringify({
    inputSha256: expectedInput,
    outputSha256: digest(buffer),
    inputBytes: CONVOLVER.length,
    outputBytes: buffer.length,
    replacedInstructions: instructions.length,
  }),
);
compatible.destroy();
original.destroy();
